/**
 * 获取指定日期的属性详情
 * @param {string} dateStr - 格式 YYYY-MM-DD
 * @returns {{
 *   type: 'holiday' | 'workday_makeup' | 'weekend' | 'workday',
 *   name: string,
 *   isWorkday: boolean,
 *   isOffDay: boolean,
 *   badge: '休' | '班' | ''
 * }}
 */
function getDayInfo(dateStr) {
  if (!dateStr || typeof dateStr !== 'string') {
    return {
      type: 'workday',
      name: '工作日',
      isWorkday: true,
      isOffDay: false,
      badge: ''
    };
  }

  // 1. 优先命中法定节假日放假 (休)
  if (HOLIDAYS[dateStr]) {
    return {
      type: 'holiday',
      name: HOLIDAYS[dateStr],
      isWorkday: false,
      isOffDay: true,
      badge: '休'
    };
  }

  // 2. 命中调休补班上班日 (班)
  if (WORKDAYS[dateStr]) {
    return {
      type: 'workday_makeup',
      name: WORKDAYS[dateStr],
      isWorkday: true,
      isOffDay: false,
      badge: '班'
    };
  }

  // 3. 常规周六/周日判断 (普通周末休息)
  const parts = dateStr.split('-');
  if (parts.length >= 3) {
    const d = new Date(Number(parts[0]), Number(parts[1]) - 1, Number(parts[2]));
    const day = d.getDay();
    if (day === 0 || day === 6) {
      return {
        type: 'weekend',
        name: '周末',
        isWorkday: false,
        isOffDay: true,
        badge: ''
      };
    }
  }

  // 4. 常规周一至周五工作日
  return {
    type: 'workday',
    name: '工作日',
    isWorkday: true,
    isOffDay: false,
    badge: ''
  };
}

/**
 * 判断指定日期是否为非工作日（周末或法定节假日，出勤全计加班，休息全计入加班）
 * @param {string} dateStr - 格式 YYYY-MM-DD
 * @returns {boolean} true: 休息日 (周末或节假日); false: 工作日 (周一至周五或调休上班日)
 */
function isOffDay(dateStr) {
  return getDayInfo(dateStr).isOffDay;
}

/**
 * 判断指定日期是否为工作日（普通工作日或调休上班日）
 * @param {string} dateStr - 格式 YYYY-MM-DD
 * @returns {boolean} true: 工作日; false: 休息日
 */
function isWorkday(dateStr) {
  return getDayInfo(dateStr).isWorkday;
}

